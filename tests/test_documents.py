class Agent:
    """Just enough of a core for the bridge messages under test."""

    registry = None

    def __init__(self, config, vault):
        self.config = config
        self.vault = vault


def session(config, vault):
    from ranger.bridge import Session

    sent: list[dict] = []
    return Session(agent=Agent(config, vault), send=sent.append), sent


class Finished:
    def __init__(self, name, ok, summary):
        self.name, self.ok, self.summary = name, ok, summary


def test_the_preview_event_only_follows_a_file_that_exists(vault, config):
    """**Never lie about state.** The `document` event is what starts the
    assembly animation in the browser, so it is only ever sent for a file that
    is on disk. A generation that failed draws nothing at all.
    """
    made = make(vault, config, kind="docx")
    talk, sent = session(config, vault)

    talk._document_landed(Finished("write_document", False, made.relative))
    assert [e for e in sent if e["kind"] == "document"] == [], "a failure is not an assembly"

    sent.clear()
    talk._document_landed(Finished("write_document", True, "Ranger/drafts/not-there.docx"))
    assert [e for e in sent if e["kind"] == "document"] == []

    sent.clear()
    talk._document_landed(Finished("draft_and_hold", True, made.relative))
    assert [e for e in sent if e["kind"] == "document"] == []

    sent.clear()
    talk._document_landed(Finished("write_document", True, made.relative))
    events = [e for e in sent if e["kind"] == "document"]
    assert len(events) == 1
    assert events[0]["assembly"] is True
    assert events[0]["name"] == made.path.name
    # `kind` is the frame type on this socket, so the document's own format
    # travels as `format`. Sending both under one name made the preview arrive
    # claiming to be a file of kind "document", which is nothing.
    assert events[0]["kind"] == "document"
    assert events[0]["format"] == "docx"
    assert events[0]["url"].startswith("/document/")
    assert events[0]["caveat"]


