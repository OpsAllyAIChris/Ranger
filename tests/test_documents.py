def test_gp_export_writes_a_workbook_with_no_formulas_in_it(vault, config):
    """The first thing item D is used for, and deliberately the simplest: the
    preview's formula caveat cannot bite, because there are none."""
    from datetime import datetime

    from ranger import gp

    gp.record(config, vault, "44000", period="2026-08", now=datetime(2026, 9, 1, 9, 0))
    gp.record(config, vault, "45500", period="2026-08", now=datetime(2026, 9, 3, 16, 30))
    gp.record(config, vault, "48250", period="2026-09", now=datetime(2026, 9, 8, 11, 15))

    made = gp.export(config, vault, date(2026, 9, 8))
    assert made.kind == "xlsx"
    assert "<f>" not in sheet_xml(made.path)

    rendered = pv.preview(made.path, root=config.vault.root)
    names = [sheet.name for sheet in rendered.sheets]
    assert "By month" in names and "Summary" in names
    assert "Superseded" in names, "a corrected figure is part of the record"

    summary = rendered.sheets[names.index("Summary")]
    flat = {row.cells[0]: row.cells[1] for row in summary.rows if len(row.cells) > 1}
    assert flat["Year to date"] == "$93,750.00", "45,500 not 44,000"

    months = rendered.sheets[names.index("By month")]
    assert months.rows[0].cells == ("Period", "Gross profit", "Recorded")
    assert [row.cells[1] for row in months.rows[1:]] == ["$45,500.00", "$48,250.00"]


