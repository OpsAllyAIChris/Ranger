def reachable(*names: str) -> set[str]:
    """Every module reachable from these, function-level imports included."""
    import ast

    seen: set[str] = set()
    queue = list(names)
    while queue:
        name = queue.pop()
        if name in seen:
            continue
        seen.add(name)
        source = RANGER / f"{name}.py"
        if not source.is_file():
            continue
        for node in ast.walk(ast.parse(source.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom) and node.level and node.module:
                queue.append(node.module.split(".")[0])
            elif isinstance(node, ast.ImportFrom) and node.level and not node.module:
                queue.extend(alias.name for alias in node.names)
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    seen.add(alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom) and node.module:
                seen.add(node.module.split(".")[0])
    return seen


def test_the_preview_parses_with_neither_of_the_libraries_that_write(vault, config):
    """**The round trip has to go through a different implementation.**

    If the preview used python-docx and openpyxl, a preview that agreed with the
    file would only be telling us those libraries are self-consistent. Reading
    the OOXML parts with zipfile and ElementTree makes the agreement evidence
    about the file.
    """
    graph = reachable("preview")
    for library in ("docx", "openpyxl", "reportlab", "lxml"):
        assert library not in graph, (
            f"preview.py reaches {library}. The preview is the independent "
            "implementation; it cannot borrow the writer's."
        )
    assert "zipfile" in graph and "xml" in graph


