def test_the_word_file_holds_the_text_and_the_table(vault, config):
    """Asserted on the OOXML part, not on python-docx reading itself back."""
    made = make(vault, config, kind="docx")
    body = part(made.path, "word/document.xml").decode("utf-8")

    assert "Where we are" in body
    assert "Wexxar case sealers, 5 units" in body
    for cell in ("Period", "Gross profit", "2026-08", "45500"):
        assert cell in body
    tree = ElementTree.fromstring(part(made.path, "word/document.xml"))
    tables = list(tree.iter(f"{W}tbl"))
    assert len(tables) == 1
    assert [_text(cell) for cell in tables[0].iter(f"{W}tc")][:2] == ["Period", "Gross profit"]


