def test_the_preview_reads_the_file_and_not_the_content_it_was_made_from(
    vault, config, tmp_path
):
    """**Preview the artifact, not the intention.**

    A preview built upstream of generation agrees with the export right up
    until it does not, and the place that disagreement surfaces is in front of
    a customer. So: write a document, change the bytes on disk, and require the
    preview to show what is in the file.
    """
    made = make(vault, config, kind="docx", blocks=(docs.text("The price is 12,000."),))

    tampered = tmp_path / "tampered.docx"
    with zipfile.ZipFile(made.path) as source, zipfile.ZipFile(tampered, "w") as out:
        for item in source.infolist():
            data = source.read(item.filename)
            if item.filename == "word/document.xml":
                data = data.replace(b"The price is 12,000.", b"The price is 21,000.")
            out.writestr(item, data)

    rendered = pv.preview(tampered)
    texts = [block["text"] for block in rendered.blocks]
    assert "The price is 21,000." in texts, "the preview must show the file"
    assert "The price is 12,000." not in texts


