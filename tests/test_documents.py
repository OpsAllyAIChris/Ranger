"""Item D and D2: generated documents, and the preview that renders them back.

Two rules from the operator shape this file, and both are about not being able
to trust the obvious check.

**You cannot validate with the library that wrote the file.** python-docx
reading back what python-docx wrote proves python-docx is self-consistent,
which was never the question. The consumers are Word and Excel and neither can
be run here. So these tests unzip the OOXML and assert on the parts, read the
PDF with a library that did not write it, and lean on `ranger/preview.py` --
stdlib only, no docx, no openpyxl -- as the independent implementation the
round trip goes through. **The operator opening a file in the real application
is still the only green light.**

**Preview the artifact, not the intention.** The preview must render from the
file on disk after generation, never from the content that was about to become
a file. `test_the_preview_reads_the_file_and_not_the_content_it_was_made_from`
is the test that holds that: it tampers with a file on disk and requires the
preview to show what is in the file.

Three security holes in this path are real rather than theoretical, and each
has a test: Excel evaluating a formula that came out of a customer email,
reportlab loading a file off disk because a paragraph contained `<img>`, and
Word field codes arriving in pasted text.
"""

from __future__ import annotations

import json
import re
import shutil
import zipfile
from datetime import date
from pathlib import Path
from xml.etree import ElementTree

import pytest

from ranger import documents as docs
from ranger import preview as pv

RANGER = Path(__file__).resolve().parent.parent / "ranger"

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def spec(**overrides) -> docs.Spec:
    base = dict(
        title="Q4 film pricing",
        subtitle="Illes Foods",
        blocks=(
            docs.heading("Where we are", 1),
            docs.text("Rod asked for the numbers by Thursday."),
            docs.bullet("Wexxar case sealers, 5 units"),
            docs.table(
                ["Period", "Gross profit"],
                [["2026-08", "45500"], ["2026-09", "48250"]],
                name="GP",
            ),
        ),
        source="Generated by Jarvis from the Illes note.",
    )
    base.update(overrides)
    return docs.Spec(**base)


def make(vault, config, which=None, kind="docx", **overrides):
    return docs.generate(
        vault,
        config.vault.drafts,
        which or spec(**overrides),
        kind,
        today=date(2026, 9, 8),
    )


def _text(node) -> str:
    return "".join(part.text or "" for part in node.iter(f"{W}t")).strip()


def part(path: Path, name: str) -> bytes:
    with zipfile.ZipFile(path) as archive:
        return archive.read(name)


def sheet_xml(path: Path) -> str:
    with zipfile.ZipFile(path) as archive:
        return "".join(
            archive.read(name).decode("utf-8")
            for name in archive.namelist()
            if name.startswith("xl/worksheets/")
        )


